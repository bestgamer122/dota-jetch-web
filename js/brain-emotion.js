var BrainEmotion = {
  patterns: {
    sad: [/груст|печаль|расстроен|плохо мне|тяжело|устал от доты|плохо игр/i, /не получается|не могу|сдаюсь/i],
    angry: [/бесит|ненавижу|злюсь|тильт|раздражает|достал|заткнись|тупой|дурак/i, /долбо|бля|ебан|хуй|пиздец/i],
    happy: [/рад|круто|отлично|супер|класс|кайф|нравится|люблю|победа|выиграл/i, /спасибо|благодар/i],
    tired: [/устал|спать|вымотан|нет сил|не могу больше|заеба|заебал/i],
    excited: [/ура|ееее|вау|ого|ничего себе|победил|выиграл|пятёрка/i],
    confused: [/не понимаю|что|как это|хз|хер знает|непонятно|запутался/i],
    curious: [/интересно|а что если|а как|расскажи подробнее|почему|зачем/i]
  },
  detect: function (q) {
    var s = String(q || "");
    var detected = [];
    for (var mood in this.patterns) {
      if (!this.patterns.hasOwnProperty(mood)) continue;
      for (var i = 0; i < this.patterns[mood].length; i++) {
        if (this.patterns[mood][i].test(s)) { detected.push({ mood: mood, strength: i === 0 ? 1 : 2 }); break; }
      }
    }
    if (!detected.length) return null;
    detected.sort(function (a, b) { return b.strength - a.strength; });
    return detected[0];
  },
  reactions: {
    sad: ["Слышу, что тебе нелегко. Это нормально — Dota может выматывать. Отдохни, посмотри аналитику спокойно.", "Понимаю, бывает. Не дави на себя. Каждый проигрыш — ступенька вверх.", "Держись. Загружай матч, разберём что можно было сделать иначе."],
    angry: ["Вижу, что накипело. Давай спокойно — если хочешь, разберём игру.", "Понимаю, тильт сильный. Не принимай решения сейчас. 10 минут перерыв — и будет легче.", "Если что-то бесит в игре — расскажи. Я не буду оценивать."],
    happy: ["Отлично! Рад за тебя. Что нового хорошего?", "Круто! Видно, что у тебя хорошее настроение :)", "Супер! Продолжай в том же духе."],
    tired: ["Понимаю, устал. Может, отложить доту на потом? Сон важнее MMR.", "Не мучай себя. Игра на усталости — только проигрыши.", "Слышу. Если хочешь — поговорим, если нет — просто отдохни."],
    excited: ["Ого, чувствую энергию! Что произошло?", "Рад видеть такой настрой!", "Кайф! С таким настроением только побеждать."],
    confused: ["Давай разберёмся вместе. Спроси подробнее.", "Не переживай, разберём. В чём затык?", "Если что-то непонятно — спроси прямо :)"],
    curious: ["Отличный вопрос! Давай копнём глубже.", "Люблю любопытных. Что именно интересует?", "Спрашивай — расскажу всё, что знаю."]
  },
  respond: function (emotion) {
    if (!emotion) return null;
    var arr = this.reactions[emotion.mood];
    if (!arr || !arr.length) return null;
    return arr[Math.floor(Math.random() * arr.length)];
  }
};